"""Regenerate database/schema.sql from the SQLAlchemy models (MySQL dialect).

    python -m scripts.dump_schema

The models are the source of truth; this file is only for people who prefer
to create the tables with the mysql client instead of `flask --app app upgrade-db`.
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
os.environ.setdefault('DATABASE_URL', 'sqlite:///:memory:')   # nothing is connected to
sys.path.insert(0, str(ROOT))

from sqlalchemy.dialects import mysql            # noqa: E402
from sqlalchemy.schema import CreateTable        # noqa: E402

import app as app_module                         # noqa: E402
import models.technician_models                  # noqa: F401,E402

HEADER = """-- database/schema.sql
-- Generated by `python -m scripts.dump_schema` from the models. Do not edit by hand.
--
-- Customers, technicians and admins are three separate tables. Notifications,
-- messages and activity logs record the owner's role next to the id
-- (user_role / sender_role / recipient_role), because ids repeat across them.
--
-- Fresh install:   mysql -u root -p < database/schema.sql
-- (or let the app do it:  flask --app app upgrade-db)

CREATE DATABASE IF NOT EXISTS devtech CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE devtech;
"""


def main():
    dialect = mysql.dialect()
    parts = [HEADER]
    for table in app_module.db.metadata.sorted_tables:
        ddl = str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip()
        parts.append(f'\n-- {table.name}\n{ddl};\n')
    out = ROOT / 'database' / 'schema.sql'
    out.write_text(''.join(parts), encoding='utf-8')
    print(f'Wrote {out} ({len(app_module.db.metadata.sorted_tables)} tables)')


if __name__ == '__main__':
    main()
